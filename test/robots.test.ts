import { describe, expect, it } from 'vitest';
import type { Bot } from '../src/bots.js';
import { buildRobotsTxt, checkExtraRules } from '../src/robots.js';
import { parseSettings } from '../src/settings.js';

const bots: Bot[] = [
	{
		name: 'GPTBot',
		category: 'ai-training',
		operator: 'OpenAI',
		respects: 'yes',
		description: '',
		source: 'ai.robots.txt',
	},
	{ name: 'CCBot', category: 'ai-training', operator: 'CC', respects: 'yes', description: '', source: 'ai.robots.txt' },
	{ name: 'Googlebot', category: 'search', operator: 'Google', respects: 'yes', description: '', source: 'curated' },
];
const context = { sitemapUrl: 'https://example.com/sitemap-index.xml', privatePaths: ['/dashboard/', '/_tapestry/'] };

describe('buildRobotsTxt', () => {
	it('allows everything by default, keeps private paths out, links the sitemap', () => {
		const text = buildRobotsTxt(parseSettings({}, bots), context, bots);
		expect(text).toBe(
			[
				'# Generated by Tapestry SEO. Change it in the dashboard: Plugins → Tapestry SEO.',
				'',
				'User-agent: *',
				'Disallow: /dashboard/',
				'Disallow: /_tapestry/',
				'',
				'Sitemap: https://example.com/sitemap-index.xml',
				'',
			].join('\n'),
		);
	});

	it('groups blocked crawlers and adds extra rules', () => {
		const settings = parseSettings(
			{
				robots: {
					categories: { 'ai-training': 'block' },
					protectPrivate: false,
					extraRules: 'User-agent: Googlebot\nCrawl-delay: 5',
				},
			},
			bots,
		);
		const text = buildRobotsTxt(settings, context, bots);
		expect(text).toContain('User-agent: GPTBot\nUser-agent: CCBot\nDisallow: /');
		expect(text).toContain('User-agent: *\nDisallow:\n');
		expect(text).toContain('# Extra rules\nUser-agent: Googlebot\nCrawl-delay: 5');
		expect(text).not.toContain('User-agent: Googlebot\nDisallow: /');
	});

	it('leaves out the sitemap when it is off, and invalid extra rules', () => {
		const settings = parseSettings({ robots: { extraRules: 'hello world' }, sitemap: { enabled: false } }, bots);
		const text = buildRobotsTxt(settings, context, bots);
		expect(text).not.toContain('Sitemap:');
		expect(text).not.toContain('hello world');
	});
});

describe('checkExtraRules', () => {
	it('accepts directives, comments and blank lines in any case', () => {
		expect(
			checkExtraRules('# note\n\nuser-agent: X\nDISALLOW: /a\nAllow: /a/b\nCrawl-delay: 2\nSitemap: https://x/s.xml'),
		).toEqual([]);
	});

	it.each([
		['plain text', 'block everything', 1],
		['an unknown directive', 'Noindex: /x', 1],
		['HTML', '<script>alert(1)</script>', 1],
		['a control character', 'Disallow: /a\u0007', 1],
		['a later bad line', 'Disallow: /a\nwhat', 2],
	])('flags %s', (_, text, line) => {
		const problems = checkExtraRules(text);
		expect(problems[0]?.line).toBe(line);
	});

	it('limits size', () => {
		expect(checkExtraRules('#\n'.repeat(400))[0]?.message).toMatch(/lines/);
		expect(checkExtraRules('#'.repeat(10_001))[0]?.message).toMatch(/characters/);
	});
});
