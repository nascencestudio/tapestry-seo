/**
 * robots.txt from the settings (ADR 0001): one group for every blocked crawler
 * (`Disallow: /`), a `*` group keeping crawlers out of private paths, the admin's extra rules,
 * and the sitemap. Extra rules are checked line by line, so a typo can't silently produce a
 * file crawlers misread. Pure.
 */
import { BOTS, type Bot } from './bots.js';
import { isBlocked, MAX_EXTRA_RULES, type SeoSettings } from './settings.js';

export interface RobotsContext {
	/** Absolute URL of the sitemap (index), or null for none. */
	sitemapUrl: string | null;
	/** Paths kept private when `protectPrivate` is on, e.g. `/dashboard/`. */
	privatePaths: readonly string[];
}

/** Directives crawlers understand (Google, Bing, Yandex and others). */
const DIRECTIVES = new Set([
	'user-agent',
	'allow',
	'disallow',
	'crawl-delay',
	'sitemap',
	'host',
	'clean-param',
	'request-rate',
	'visit-time',
]);
export const MAX_EXTRA_LINES = 300;
// biome-ignore lint/suspicious/noControlCharactersInRegex: control characters are what's refused
const CONTROL = /[\u0000-\u0008\u000b-\u001f\u007f]/;

export interface RuleProblem {
	/** 1-based line number. */
	line: number;
	message: string;
}

/** Problems with extra rules ([] when they're fine). */
export function checkExtraRules(text: string): RuleProblem[] {
	if (text.length > MAX_EXTRA_RULES) return [{ line: 0, message: `At most ${MAX_EXTRA_RULES} characters.` }];
	const lines = text.split('\n');
	if (lines.length > MAX_EXTRA_LINES) return [{ line: 0, message: `At most ${MAX_EXTRA_LINES} lines.` }];
	const problems: RuleProblem[] = [];
	lines.forEach((raw, index) => {
		const line = raw.trim();
		if (line === '' || line.startsWith('#')) return;
		if (CONTROL.test(raw)) {
			problems.push({ line: index + 1, message: 'Contains a control character.' });
			return;
		}
		const colon = line.indexOf(':');
		const name = colon > 0 ? line.slice(0, colon).trim().toLowerCase() : '';
		if (!DIRECTIVES.has(name)) {
			problems.push({
				line: index + 1,
				message: 'Not a robots.txt rule. Expected e.g. "User-agent: name", "Disallow: /path" or a # comment.',
			});
		}
	});
	return problems;
}

const group = (agents: readonly string[], rules: readonly string[]) =>
	[...agents.map((a) => `User-agent: ${a}`), ...rules].join('\n');

/** The robots.txt text. */
export function buildRobotsTxt(settings: SeoSettings, context: RobotsContext, bots: readonly Bot[] = BOTS): string {
	const sections: string[] = ['# Generated by Tapestry SEO. Change it in the dashboard: Plugins → Tapestry SEO.'];
	const blocked = bots.filter((bot) => isBlocked(bot, settings)).map((bot) => bot.name);
	if (blocked.length > 0) sections.push(group(blocked, ['Disallow: /']));
	const privateRules = settings.robots.protectPrivate ? context.privatePaths.map((p) => `Disallow: ${p}`) : [];
	sections.push(group(['*'], privateRules.length > 0 ? privateRules : ['Disallow:']));
	const extra = settings.robots.extraRules.trim();
	if (extra && checkExtraRules(extra).length === 0) sections.push(`# Extra rules\n${extra}`);
	if (settings.sitemap.enabled && context.sitemapUrl) sections.push(`Sitemap: ${context.sitemapUrl}`);
	return `${sections.join('\n\n')}\n`;
}
